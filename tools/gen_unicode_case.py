#!/usr/bin/env python3
"""Generate include/unicode_case.h and src/unicode_case.cpp.

The simple case mapping (one code point -> one code point) of every Unicode
code point is compressed into constant-delta runs, so a lookup is a binary
search over a small table instead of a per-character branch. Python's
`str.upper()`/`str.lower()` restricted to single code points is the source;
a mapping that expands to several code points (e.g. U+00DF -> "SS") is left
out and the character is returned unchanged.

Usage: python3 tools/gen_unicode_case.py
"""

import unicodedata


def runs(upper: bool):
    pairs = []
    for cp in range(0x110000):
        ch = chr(cp)
        mapped = ch.upper() if upper else ch.lower()
        if len(mapped) == 1 and mapped != ch:
            pairs.append((cp, ord(mapped)))
    out = []
    i = 0
    while i < len(pairs):
        first, target = pairs[i]
        delta = target - first
        last = first
        j = i
        while (j + 1 < len(pairs) and pairs[j + 1][0] == pairs[j][0] + 1
               and pairs[j + 1][1] - pairs[j + 1][0] == delta):
            j += 1
            last = pairs[j][0]
        out.append((first, last, delta))
        i = j + 1
    return out


def table(name, entries):
    lines = [f"const CaseRun {name}[] = {{"]
    for first, last, delta in entries:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}, {delta}}},")
    lines.append("};")
    return "\n".join(lines)


def main():
    version = unicodedata.unidata_version
    upper = runs(True)
    lower = runs(False)
    header = f"""// Generated by tools/gen_unicode_case.py from Unicode {version}.
// Do not edit by hand; regenerate the table instead.

#ifndef OSKEL_UNICODE_CASE_H
#define OSKEL_UNICODE_CASE_H

#include <cstdint>

// Simple case mapping of a single code point (Unicode {version}). A code point
// with no mapping (including one whose full mapping expands to several code
// points) is returned unchanged.
uint32_t toUpperCodePoint(uint32_t codePoint);
uint32_t toLowerCodePoint(uint32_t codePoint);

#endif  // OSKEL_UNICODE_CASE_H
"""
    source = f"""// Generated by tools/gen_unicode_case.py from Unicode {version}.
// Do not edit by hand; regenerate the table instead.

#include "unicode_case.h"

#include <cstddef>

namespace {{

// One constant-delta run: every code point in [first, last] maps to
// `codePoint + delta`.
struct CaseRun {{
  uint32_t first;
  uint32_t last;
  int32_t delta;
}};

{table("kUpper", upper)}

{table("kLower", lower)}

uint32_t mapThrough(const CaseRun* table, size_t count, uint32_t codePoint) {{
  size_t low = 0;
  size_t high = count;
  while (low < high) {{
    size_t mid = low + (high - low) / 2;
    if (codePoint < table[mid].first) {{
      high = mid;
    }} else if (codePoint > table[mid].last) {{
      low = mid + 1;
    }} else {{
      return static_cast<uint32_t>(static_cast<int64_t>(codePoint) + table[mid].delta);
    }}
  }}
  return codePoint;
}}

}}  // namespace

uint32_t toUpperCodePoint(uint32_t codePoint) {{
  if (codePoint < 0x80) {{
    if (codePoint >= 'a' && codePoint <= 'z') return codePoint - 0x20;
    return codePoint;
  }}
  return mapThrough(kUpper, sizeof(kUpper) / sizeof(kUpper[0]), codePoint);
}}

uint32_t toLowerCodePoint(uint32_t codePoint) {{
  if (codePoint < 0x80) {{
    if (codePoint >= 'A' && codePoint <= 'Z') return codePoint + 0x20;
    return codePoint;
  }}
  return mapThrough(kLower, sizeof(kLower) / sizeof(kLower[0]), codePoint);
}}
"""
    with open("include/unicode_case.h", "w") as handle:
        handle.write(header)
    with open("src/unicode_case.cpp", "w") as handle:
        handle.write(source)
    print(f"Unicode {version}: {len(upper)} upper runs, {len(lower)} lower runs")


if __name__ == "__main__":
    main()
