// Labels to the constant tables, filled in by `emitMathLib` and used by the
// routines.
struct ConstRefs {
  CodeGen::Label expTab;  // uint64_t[256]
  CodeGen::Label logTab;  // uint64_t[256]: {invc, logc} pairs
  CodeGen::Label logTab2; // uint64_t[256]: {chi, clo} pairs
  CodeGen::Label powTab;  // uint64_t[512]: {invc, pad, logc, logctail} quads
};

void ret(CodeGen& cg) { cg.retInsn(); }

// Load a 64-bit constant into an xmm register through a GPR (movabs + movq).
// `r11` is the scratch; callers must not keep live state there.
void loadConst(CodeGen& cg, int xmm, std::uint64_t bits) {
  cg.movImm(R11, static_cast<std::int64_t>(bits));
  cg.movqToXmm(xmm, R11);
}

