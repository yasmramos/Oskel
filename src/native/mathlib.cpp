constexpr std::int64_t kPowTableBits = 7;                  // POW_LOG_TABLE_BITS
constexpr std::int64_t kPowN = 1 << kPowTableBits;

// EXP_TABLE_BITS = 7, so N = 128 and the table has 2*N = 256 entries.
constexpr std::int64_t kExpTabBits = 7;
constexpr std::int64_t kN = 1 << kExpTabBits;

// SIGN_BIAS for `pow` (0x800 << EXP_TABLE_BITS).
constexpr std::int32_t kSignBias = 0x800 << kExpTabBits;

// ---------------------------------------------------------------------------
// Small emit helpers.
