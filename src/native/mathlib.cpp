// `andMask`: dst &= mask, using r11 as scratch.
void andMask(CodeGen& cg, X64Reg dst, std::uint64_t mask) {
  cg.movImm(R11, static_cast<std::int64_t>(mask));
  cg.andReg(dst, R11);
}

// int checkint(uint64_t iy): 0 if not an int, 1 if an odd int, 2 if an even int.
// Result in eax. Clobbers rax, rcx, rdx. `done` is bound at the end.
void emitCheckint(CodeGen& cg, X64Reg iy, CodeGen::Label done) {
  CodeGen::Label ret0 = cg.newLabel();
  CodeGen::Label ret1 = cg.newLabel();
  CodeGen::Label ret2 = cg.newLabel();
  cg.movReg(Rcx, iy);
  cg.shrImm8(Rcx, 52);
  cg.andImm32(Rcx, 0x7ff);           // e
  cg.cmpImm32(Rcx, 0x3ff);
  cg.jcc(Jcc::B, ret0);
  cg.cmpImm32(Rcx, 0x3ff + 52);
  cg.jcc(Jcc::A, ret2);
  // sh = (0x3ff + 52) - e, placed in cl for the variable shifts.
  cg.movImm(Rdx, 0x3ff + 52);
  cg.subReg(Rdx, Rcx);
  cg.movReg(Rcx, Rdx);               // cl = sh
  cg.movImm(Rax, 1);
  cg.shlCl(Rax);                     // 1 << sh
  cg.subRegImm32(Rax, 1);            // mask = (1<<sh) - 1
  cg.movReg(Rdx, iy);
  cg.andReg(Rdx, Rax);
  cg.testReg(Rdx);
  cg.jcc(Jcc::Ne, ret0);
  cg.movImm(Rax, 1);
  cg.shlCl(Rax);                     // bit = 1 << sh
  cg.movReg(Rdx, iy);
  cg.andReg(Rdx, Rax);
  cg.testReg(Rdx);
  cg.jcc(Jcc::Ne, ret1);
  cg.jmp(ret2);
  cg.bind(ret0);
  cg.xorReg(Rax, Rax);
  cg.jmp(done);
  cg.bind(ret1);
  cg.movImm(Rax, 1);
  cg.jmp(done);
  cg.bind(ret2);
  cg.movImm(Rax, 2);
  cg.bind(done);
}

// double log_inline(uint64_t ix, double* tail)
//
// musl's `log_inline` from `pow.c`: a log tuned for `pow` that also returns
// ~15 extra bits of precision in `tail`. `ix` arrives in rdi; the rounded
// result returns in xmm0 and `tail` in xmm1. It is a leaf.
void emitLogInline(CodeGen& cg, CodeGen::Label label, const ConstRefs& refs) {
  cg.bind(label);
  cg.movImm(R10, static_cast<std::int64_t>(kPowOff));
  cg.movReg(R11, Rdi);
  cg.subReg(R11, R10);               // tmp = ix - OFF
  cg.movReg(Rax, R11);
  cg.shrImm8(Rax, 45);
  cg.andImm32(Rax, 127);             // i
  cg.imulImm32(Rax, Rax, 32);        // byte offset of T[i] (4 doubles)
  cg.leaRipLabel(Rcx, refs.powTab);
  cg.addReg(Rcx, Rax);
  cg.movsdToXmm(X1, Rcx, 0);         // invc
  cg.movsdToXmm(X2, Rcx, 16);        // logc
  cg.movsdToXmm(X3, Rcx, 24);        // logctail
  // iz = ix - (tmp & (0xfff<<52)); z = bits(iz)
  cg.movReg(R9, R11);
  cg.movImm(R10, 0xfff);
  cg.shlImm8(R10, 52);
  cg.andReg(R9, R10);
  cg.movReg(Rax, Rdi);
  cg.subReg(Rax, R9);                // iz
  cg.movqToXmm(X5, Rax);             // z
  // k = (int64)tmp >> 52; kd = (double)k
  cg.movReg(Rdx, R11);
  cg.movImm(Rcx, 52);
  cg.sarCl(Rdx);
  cg.cvtsi2sd(X6, Rdx);              // kd
  // zhi = bits((iz + (1<<31)) & (-1<<32)); zlo = z - zhi
  cg.movImm(R10, 1);
  cg.shlImm8(R10, 31);
  cg.addReg(Rax, R10);
  cg.movImm(R10, -1);
  cg.shlImm8(R10, 32);
  cg.andReg(Rax, R10);
  cg.movqToXmm(X4, Rax);             // zhi
  cg.movsdReg(X7, X5);
  cg.subsd(X7, X4);                  // zlo
  // rhi = zhi*invc - 1.0; rlo = zlo*invc; r = rhi + rlo
  cg.movsdReg(X8, X4);
  cg.mulsd(X8, X1);
  loadConst(cg, X9, kPowOne);
  cg.subsd(X8, X9);                  // rhi
  cg.movsdReg(X0, X7);
  cg.mulsd(X0, X1);                  // rlo
  cg.movsdReg(X10, X8);
  cg.addsd(X10, X0);                 // r
  // t1 = kd*Ln2hi + logc; t2 = t1 + r; lo1 = kd*Ln2lo + logctail;
  // lo2 = t1 - t2 + r
  loadConst(cg, X11, kPowLn2hi);
  cg.mulsd(X11, X6);
  cg.addsd(X11, X2);                 // t1
  cg.movsdReg(X4, X11);
  cg.addsd(X4, X10);                 // t2
  loadConst(cg, X7, kPowLn2lo);
  cg.mulsd(X7, X6);
  cg.addsd(X7, X3);                  // lo1
  cg.movsdReg(X2, X11);
  cg.subsd(X2, X4);
  cg.addsd(X2, X10);                 // lo2
  // ar = A0*r; ar2 = r*ar; ar3 = r*ar2
  loadConst(cg, X1, kPowA0);
  cg.mulsd(X1, X10);                 // ar
  cg.movsdReg(X5, X10);
  cg.mulsd(X5, X1);                  // ar2
  cg.movsdReg(X3, X10);
  cg.mulsd(X3, X5);                  // ar3
  // arhi = A0*rhi; arhi2 = rhi*arhi; hi = t2 + arhi2
  loadConst(cg, X9, kPowA0);
  cg.mulsd(X9, X8);                  // arhi
  cg.movsdReg(X6, X8);
  cg.mulsd(X6, X9);                  // arhi2
  cg.movsdReg(X11, X4);
  cg.addsd(X11, X6);                 // hi
  // lo3 = rlo*(ar + arhi)
  cg.addsd(X9, X1);                  // ar + arhi
  cg.mulsd(X0, X9);                  // lo3
  // lo4 = t2 - hi + arhi2
  cg.movsdReg(X8, X4);
  cg.subsd(X8, X11);
  cg.addsd(X8, X6);                  // lo4
  // p = ar3*(A1 + r*A2 + ar2*(A3 + r*A4 + ar2*(A5 + r*A6)))
  loadConst(cg, X4, kPowA6);
  cg.mulsd(X4, X10);
  loadConst(cg, X6, kPowA5);
  cg.addsd(X6, X4);
  cg.mulsd(X6, X5);                  // ar2*(...)
  loadConst(cg, X4, kPowA4);
  cg.mulsd(X4, X10);
  loadConst(cg, X9, kPowA3);
  cg.addsd(X9, X4);
  cg.addsd(X9, X6);
  cg.mulsd(X9, X5);                  // ar2*(A3 + r*A4 + ar2*(A5 + r*A6))
  loadConst(cg, X4, kPowA2);
  cg.mulsd(X4, X10);
  loadConst(cg, X6, kPowA1);
  cg.addsd(X6, X4);
  cg.addsd(X6, X9);
  cg.mulsd(X3, X6);                  // p
  // lo = lo1 + lo2 + lo3 + lo4 + p ; y = hi + lo ; tail = hi - y + lo
  cg.addsd(X7, X2);                  // lo1 + lo2
  cg.addsd(X7, X0);                  // + lo3
  cg.addsd(X7, X8);                  // + lo4
  cg.addsd(X7, X3);                  // + p = lo
  cg.movsdReg(X0, X11);
  cg.addsd(X0, X7);                  // y = hi + lo
  cg.movsdReg(X1, X11);
  cg.subsd(X1, X0);
  cg.addsd(X1, X7);                  // tail = hi - y + lo
  ret(cg);
}

// double pow(double x, double y): x in xmm0, y in xmm1; result in xmm0.
void emitPow(CodeGen& cg, CodeGen::Label label, CodeGen::Label expCore,
             CodeGen::Label logInline) {
  CodeGen::Label specials = cg.newLabel();
  CodeGen::Label general = cg.newLabel();
  CodeGen::Label retOne = cg.newLabel();
  CodeGen::Label retZero = cg.newLabel();
  CodeGen::Label retXY = cg.newLabel();
  CodeGen::Label retYY = cg.newLabel();
  CodeGen::Label zinfIy = cg.newLabel();
  CodeGen::Label notZinfIy = cg.newLabel();
  CodeGen::Label zinfIx = cg.newLabel();
  CodeGen::Label notZinfIx = cg.newLabel();
  CodeGen::Label negX = cg.newLabel();
  CodeGen::Label negXOk = cg.newLabel();
  CodeGen::Label negXMask = cg.newLabel();
  CodeGen::Label retNaN = cg.newLabel();
  CodeGen::Label yBig = cg.newLabel();
  CodeGen::Label ySmall = cg.newLabel();
  CodeGen::Label ySmallAdd = cg.newLabel();
  CodeGen::Label oflow = cg.newLabel();
  CodeGen::Label uflow = cg.newLabel();
  CodeGen::Label subnormX = cg.newLabel();
  CodeGen::Label retX2 = cg.newLabel();
  CodeGen::Label general2 = cg.newLabel();
  CodeGen::Label checkIntA = cg.newLabel();
  CodeGen::Label checkIntB = cg.newLabel();
  CodeGen::Label done = cg.newLabel();

  cg.bind(label);
  cg.xorps(X12, X12);                // sign_bias = 0
  cg.movqFromXmm(Rdi, X0);           // ix
  cg.movqFromXmm(R8, X1);            // iy
  cg.movReg(R9, Rdi);
  cg.shrImm8(R9, 52);                // topx
  cg.movReg(R10, R8);
  cg.shrImm8(R10, 52);               // topy

  // if (topx - 1 >= 0x7fe || (topy & 0x7ff) - 0x3be >= 0x80) specials
  cg.movReg(Rax, R9);
  cg.subRegImm32(Rax, 1);
  cg.cmpImm32(Rax, 0x7fe);
  cg.jcc(Jcc::Ae, specials);
  cg.movReg(Rax, R10);
  cg.andImm32(Rax, 0x7ff);
  cg.subRegImm32(Rax, 0x3be);
  cg.cmpImm32(Rax, 0x43e - 0x3be);
  cg.jcc(Jcc::Ae, specials);
  cg.jmp(general);

  cg.bind(specials);
  // zeroinfnan(iy): (2*iy - 1) >= (2*inf - 1)
  cg.movReg(Rax, R8);
  cg.shlImm8(Rax, 1);
  cg.subRegImm32(Rax, 1);
  cg.movImm(R11, static_cast<std::int64_t>(0xffdfffffffffffffULL));
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::Ae, zinfIy);
  cg.jmp(notZinfIy);

  cg.bind(zinfIy);
  // if (2*iy == 0) return 1.0
  cg.movReg(Rax, R8);
  cg.shlImm8(Rax, 1);
  cg.testReg(Rax);
  cg.jcc(Jcc::Eq, retOne);
  // if (ix == bits(1.0)) return 1.0
  cg.movImm(R11, static_cast<std::int64_t>(kPowOne));
  cg.cmpReg(Rdi, R11);
  cg.jcc(Jcc::Eq, retOne);
  // if (2*ix > 2*inf || 2*iy > 2*inf) return x + y
  cg.movImm(R11, static_cast<std::int64_t>(0xffe0000000000000ULL));
  cg.movReg(Rax, Rdi);
  cg.shlImm8(Rax, 1);
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::A, retXY);
  cg.movReg(Rax, R8);
  cg.shlImm8(Rax, 1);
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::A, retXY);
  // if (2*ix == 2*bits(1.0)) return 1.0
  cg.movImm(R11, static_cast<std::int64_t>(2ULL * kPowOne));
  cg.movReg(Rax, Rdi);
  cg.shlImm8(Rax, 1);
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::Eq, retOne);
  // if ((2*ix < 2*bits(1.0)) == !(iy>>63)) return 0.0
  cg.movReg(Rax, Rdi);
  cg.shlImm8(Rax, 1);
  cg.cmpReg(Rax, R11);
  cg.setcc(Jcc::B, Rax);             // al = (2*ix < 2*one)
  cg.movzx(Rax, Rax);
  cg.movReg(Rcx, R8);
  cg.shrImm8(Rcx, 63);               // iy>>63
  cg.xorReg(Rcx, Rax);               // 0 when equal
  cg.testReg(Rcx);
  cg.jcc(Jcc::Eq, retZero);
  cg.jmp(retYY);

  cg.bind(notZinfIy);
  // zeroinfnan(ix): (2*ix - 1) >= (2*inf - 1)
  cg.movReg(Rax, Rdi);
  cg.shlImm8(Rax, 1);
  cg.subRegImm32(Rax, 1);
  cg.movImm(R11, static_cast<std::int64_t>(0xffdfffffffffffffULL));
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::Ae, zinfIx);
  cg.jmp(notZinfIx);

  cg.bind(zinfIx);
  // x2 = x*x
  cg.movsdReg(X2, X0);
  cg.mulsd(X2, X2);
  // if (ix >> 63 && checkint(iy) == 1) x2 = -x2
  cg.movReg(Rax, Rdi);
  cg.shrImm8(Rax, 63);
  cg.testReg(Rax);
  cg.jcc(Jcc::Eq, notZinfIx);        // no sign flip
  emitCheckint(cg, R8, checkIntA);
  cg.cmpImm32(Rax, 1);
  cg.jcc(Jcc::Ne, notZinfIx);
  loadConst(cg, X3, kSignMask);
  cg.xorps(X2, X3);                  // x2 = -x2
  cg.jmp(notZinfIx);
  cg.bind(notZinfIx);
  // if (iy >> 63) return 1/x2 else return x2  (only reached from zinfIx)
  // NOTE: control from `notZinfIy` falls straight through here, so guard it.
  cg.movReg(Rax, Rdi);
  cg.shlImm8(Rax, 1);
  cg.subRegImm32(Rax, 1);
  cg.movImm(R11, static_cast<std::int64_t>(0xffdfffffffffffffULL));
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::B, negX);              // x is a normal finite value
  // x is 0/inf/nan: return the computed x2 (or its reciprocal)
  cg.movReg(Rax, R8);
  cg.shrImm8(Rax, 63);
  cg.testReg(Rax);
  cg.jcc(Jcc::Eq, retX2);
  loadConst(cg, X3, kPowOne);
  cg.divsd(X3, X2);
  cg.movsdReg(X0, X3);
  cg.jmp(done);
  cg.bind(retX2);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(negX);
  // if (ix >> 63) { yint = checkint(iy); ... }
  cg.movReg(Rax, Rdi);
  cg.shrImm8(Rax, 63);
  cg.testReg(Rax);
  cg.jcc(Jcc::Eq, negXOk);           // x >= 0
  emitCheckint(cg, R8, checkIntB);
  cg.cmpImm32(Rax, 0);
  cg.jcc(Jcc::Eq, retNaN);
  cg.cmpImm32(Rax, 1);
  cg.jcc(Jcc::Ne, negXMask);
  // sign_bias = SIGN_BIAS
  cg.movImm(R11, kSignBias);
  cg.movqToXmm(X12, R11);
  cg.bind(negXMask);
  andMask(cg, Rdi, kAbsMask);
  cg.movReg(R9, Rdi);
  cg.shrImm8(R9, 52);                // topx = (ix >> 52) & 0x7ff
  cg.andImm32(R9, 0x7ff);

  cg.bind(negXOk);
  // if ((topy & 0x7ff) - 0x3be >= 0x80)
  cg.movReg(Rax, R10);
  cg.andImm32(Rax, 0x7ff);
  cg.subRegImm32(Rax, 0x3be);
  cg.cmpImm32(Rax, 0x43e - 0x3be);
  cg.jcc(Jcc::Ae, yBig);
  // |y| is in the normal range: fall through to the general path, exactly as
  // musl does (the `topx == 0` normalization is the first thing there).
  cg.jmp(general);

  cg.bind(yBig);
  // if (ix == bits(1.0)) return 1.0
  cg.movImm(R11, static_cast<std::int64_t>(kPowOne));
  cg.cmpReg(Rdi, R11);
  cg.jcc(Jcc::Eq, retOne);
  // if ((topy & 0x7ff) < 0x3be) return (ix > bits(1.0)) ? 1+y : 1-y
  cg.movReg(Rax, R10);
  cg.andImm32(Rax, 0x7ff);
  cg.cmpImm32(Rax, 0x3be);
  cg.jcc(Jcc::B, ySmall);
  // return ((ix > bits(1.0)) == (topy < 0x800)) ? oflow : uflow
  cg.movReg(Rax, Rdi);
  cg.cmpReg(Rax, R11);
  cg.setcc(Jcc::A, Rax);             // (ix > 1.0)
  cg.movzx(Rax, Rax);
  cg.movReg(Rcx, R10);
  cg.cmpImm32(Rcx, 0x800);
  cg.setcc(Jcc::B, Rcx);             // (topy < 0x800)
  cg.movzx(Rcx, Rcx);
  cg.cmpReg(Rax, Rcx);
  cg.jcc(Jcc::Eq, oflow);
  cg.jmp(uflow);

  cg.bind(ySmall);
  // |y| < 2^-65, x^y ~= 1 + y*log(x). Reached only from `yBig`, which has
  // already handled `ix == bits(1.0)`, so no check is needed here.
  // return ix > bits(1.0) ? 1.0 + y : 1.0 - y
  loadConst(cg, X2, kPowOne);
  cg.movReg(Rax, Rdi);
  cg.cmpReg(Rax, R11);
  cg.jcc(Jcc::A, ySmallAdd);
  cg.subsd(X2, X1);
  cg.movsdReg(X0, X2);
  cg.jmp(done);
  cg.bind(ySmallAdd);
  cg.addsd(X2, X1);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(oflow);
  loadConst(cg, X0, kP769);
  cg.mulsd(X0, X0);
  cg.jmp(done);
  cg.bind(uflow);
  loadConst(cg, X0, kP767);
  cg.mulsd(X0, X0);
  cg.jmp(done);

  cg.bind(subnormX);
  // ix = bits(x*0x1p52) & 0x7fff...; ix -= 52<<52
  loadConst(cg, X2, kP52);
  cg.mulsd(X2, X0);
  cg.movqFromXmm(Rdi, X2);
  andMask(cg, Rdi, kAbsMask);
  cg.movImm(R11, 52);
  cg.shlImm8(R11, 52);
  cg.subReg(Rdi, R11);
  cg.jmp(general);

  cg.bind(general);
  // if (topx == 0) normalize the subnormal
  cg.testReg(R9);
  cg.jcc(Jcc::Eq, subnormX);

  cg.bind(general2);
  cg.movqFromXmm(Rsi, X1);           // save y across log_inline
  cg.callLabel(logInline);
  // yhi = bits(iy & (-1<<27)); ylo = y - yhi
  cg.movReg(Rax, R8);
  cg.movImm(R10, -1);
  cg.shlImm8(R10, 27);
  cg.andReg(Rax, R10);
  cg.movqToXmm(X2, Rax);             // yhi
  cg.movqToXmm(X3, Rsi);             // y
  cg.movsdReg(X4, X3);
  cg.subsd(X4, X2);                  // ylo
  // lhi = bits(hi) & (-1<<27); llo = hi - lhi + lo
  cg.movqFromXmm(Rax, X0);
  cg.andReg(Rax, R10);
  cg.movqToXmm(X5, Rax);             // lhi
  cg.movsdReg(X6, X0);
  cg.subsd(X6, X5);
  cg.addsd(X6, X1);                  // llo
  // ehi = yhi*lhi; elo = ylo*lhi + y*llo
  cg.movsdReg(X7, X2);
  cg.mulsd(X7, X5);                  // ehi
  cg.movsdReg(X8, X4);
  cg.mulsd(X8, X5);                  // ylo*lhi
  cg.movsdReg(X9, X3);
  cg.mulsd(X9, X6);                  // y*llo
  cg.addsd(X8, X9);                  // elo
  cg.movsdReg(X0, X7);
  cg.movsdReg(X1, X8);
  cg.movqFromXmm(Rdx, X12);          // sign_bias
  cg.callLabel(expCore);
  cg.jmp(done);

  cg.bind(retOne);
  loadConst(cg, X0, kPowOne);
  cg.jmp(done);
  cg.bind(retZero);
  cg.xorps(X0, X0);
  cg.jmp(done);
  cg.bind(retXY);
  cg.addsd(X0, X1);
  cg.jmp(done);
  cg.bind(retYY);
  cg.movsdReg(X0, X1);
  cg.mulsd(X0, X0);
  cg.jmp(done);
  cg.bind(retNaN);
  // musl's `__math_invalid(x)` is `(x - x) / (x - x)`, i.e. 0/0 = NaN.
  cg.movsdReg(X2, X0);
  cg.subsd(X2, X0);
  cg.divsd(X2, X2);
  cg.movsdReg(X0, X2);

  cg.bind(done);
  ret(cg);
}


