// double log(double x): x arrives in xmm0, the result returns in xmm0.
void emitLog(CodeGen& cg, CodeGen::Label label, const ConstRefs& refs) {
  CodeGen::Label closeTo1 = cg.newLabel();
  CodeGen::Label retZero = cg.newLabel();
  CodeGen::Label nonPositive = cg.newLabel();
  CodeGen::Label retNegInf = cg.newLabel();
  CodeGen::Label retX = cg.newLabel();
  CodeGen::Label retNaN = cg.newLabel();
  CodeGen::Label subnormal = cg.newLabel();
  CodeGen::Label general = cg.newLabel();
  CodeGen::Label done = cg.newLabel();
  (void)subnormal;

  cg.bind(label);
  cg.movqFromXmm(R8, X0);            // r8 = ix
  cg.movReg(R9, R8);
  cg.shrImm8(R9, 48);                // top = top16(x)

  // if (ix - LO < HI - LO) closeTo1
  cg.movReg(R10, R8);
  cg.movImm(R11, static_cast<std::int64_t>(kLogLo));
  cg.subReg(R10, R11);               // ix - LO
  cg.movImm(R11, static_cast<std::int64_t>(kLogHi - kLogLo));
  cg.cmpReg(R10, R11);
  cg.jcc(Jcc::B, closeTo1);

  // if (top - 0x0010 >= 0x7ff0 - 0x0010) nonPositive
  cg.movReg(R10, R9);
  cg.subRegImm32(R10, 0x0010);
  cg.cmpImm32(R10, 0x7ff0 - 0x0010);
  cg.jcc(Jcc::Ae, nonPositive);
  cg.jmp(general);

  cg.bind(closeTo1);
  // if (ix == 1.0) return 0.0
  cg.movImm(R11, static_cast<std::int64_t>(kOne));
  cg.cmpReg(R8, R11);
  cg.jcc(Jcc::Eq, retZero);
  // r = x - 1.0
  loadConst(cg, X1, kOne);
  cg.movsdReg(X2, X0);
  cg.subsd(X2, X1);                  // X2 = r
  cg.movsdReg(X3, X2);
  cg.mulsd(X3, X3);                  // X3 = r2
  cg.movsdReg(X4, X2);
  cg.mulsd(X4, X3);                  // X4 = r3
  // y = r3 * (B1 + r*B2 + r2*B3 + r3*(B4 + r*B5 + r2*B6
  //                            + r3*(B7 + r*B8 + r2*B9 + r3*B10)))
  loadConst(cg, X5, kLogB10);
  cg.mulsd(X5, X4);                  // r3*B10
  loadConst(cg, X6, kLogB9);
  cg.mulsd(X6, X3);                  // r2*B9
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB8);
  cg.mulsd(X6, X2);                  // r*B8
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB7);
  cg.addsd(X5, X6);                  // B7 + ...
  cg.mulsd(X5, X4);                  // r3*(...)
  loadConst(cg, X6, kLogB6);
  cg.mulsd(X6, X3);
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB5);
  cg.mulsd(X6, X2);
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB4);
  cg.addsd(X5, X6);
  cg.mulsd(X5, X4);                  // r3*(...)
  loadConst(cg, X6, kLogB3);
  cg.mulsd(X6, X3);
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB2);
  cg.mulsd(X6, X2);
  cg.addsd(X5, X6);
  loadConst(cg, X6, kLogB1);
  cg.addsd(X5, X6);                  // B1 + ...
  cg.mulsd(X5, X4);                  // y = r3*(...)

  // w = r*0x1p27; rhi = r + w - w; rlo = r - rhi
  loadConst(cg, X6, kP27);
  cg.mulsd(X6, X2);                  // w
  cg.movsdReg(X7, X2);
  cg.addsd(X7, X6);
  cg.subsd(X7, X6);                  // rhi = r + w - w
  cg.movsdReg(X8, X2);
  cg.subsd(X8, X7);                  // rlo = r - rhi
  // w = rhi*rhi*B0
  cg.movsdReg(X9, X7);
  cg.mulsd(X9, X7);
  loadConst(cg, X10, kLogB0);
  cg.mulsd(X9, X10);                 // w
  // hi = r + w; lo = r - hi + w
  cg.movsdReg(X10, X2);
  cg.addsd(X10, X9);                 // hi
  cg.movsdReg(X11, X2);
  cg.subsd(X11, X10);
  cg.addsd(X11, X9);                 // lo = r - hi + w
  // lo += B0 * rlo * (rhi + r)
  cg.movsdReg(X9, X8);
  loadConst(cg, X6, kLogB0);
  cg.mulsd(X9, X6);                  // B0*rlo
  cg.movsdReg(X6, X7);
  cg.addsd(X6, X2);                  // rhi + r
  cg.mulsd(X9, X6);
  cg.addsd(X11, X9);                 // lo += ...
  cg.addsd(X5, X11);                 // y += lo
  cg.addsd(X5, X10);                 // y += hi
  cg.movsdReg(X0, X5);
  cg.jmp(done);

  cg.bind(nonPositive);
  // if (ix*2 == 0) return divzero(1) = -inf
  cg.movReg(R10, R8);
  cg.shlImm8(R10, 1);
  cg.testReg(R10);
  cg.jcc(Jcc::Eq, retNegInf);
  // if (ix == inf) return x
  cg.movImm(R11, static_cast<std::int64_t>(kInf));
  cg.cmpReg(R8, R11);
  cg.jcc(Jcc::Eq, retX);
  // if ((top & 0x8000) || (top & 0x7ff0) == 0x7ff0) return invalid(x) = nan
  cg.testImm32(R9, 0x8000);
  cg.jcc(Jcc::Ne, retNaN);
  cg.movReg(R10, R9);
  cg.andImm32(R10, 0x7ff0);
  cg.cmpImm32(R10, 0x7ff0);
  cg.jcc(Jcc::Eq, retNaN);
  // subnormal: ix = bits(x*0x1p52) - (52<<52)
  loadConst(cg, X1, kP52);
  cg.mulsd(X1, X0);
  cg.movqFromXmm(R8, X1);
  cg.movImm(R10, 52);
  cg.shlImm8(R10, 52);
  cg.subReg(R8, R10);
  cg.jmp(general);

  cg.bind(general);
  // tmp = ix - OFF; i = (tmp >> 45) % 128; k = (int64)tmp >> 52;
  // iz = ix - (tmp & 0xfff<<52); z = bits(iz)
  cg.movImm(R10, static_cast<std::int64_t>(kLogOff));
  cg.movReg(R11, R8);
  cg.subReg(R11, R10);               // r11 = tmp
  cg.movReg(Rax, R11);
  cg.shrImm8(Rax, 45);
  cg.andImm32(Rax, 127);             // i
  cg.imulImm32(Rax, Rax, 16);        // byte offset of T[i]
  cg.leaRipLabel(Rcx, refs.logTab);
  cg.addReg(Rcx, Rax);
  cg.movsdToXmm(X1, Rcx, 0);         // invc
  cg.movsdToXmm(X2, Rcx, 8);         // logc
  cg.leaRipLabel(Rdx, refs.logTab2);
  cg.addReg(Rdx, Rax);
  cg.movsdToXmm(X3, Rdx, 0);         // chi
  cg.movsdToXmm(X4, Rdx, 8);         // clo
  // iz = ix - (tmp & 0xfff<<52)
  cg.movReg(R9, R11);
  cg.movImm(R10, 0xfff);
  cg.shlImm8(R10, 52);
  cg.andReg(R9, R10);
  cg.movReg(Rax, R8);
  cg.subReg(Rax, R9);                // iz
  cg.movqToXmm(X5, Rax);             // z
  // k = (int64)tmp >> 52
  cg.movReg(Rdx, R11);
  cg.movImm(Rcx, 52);
  cg.sarCl(Rdx);                     // k (integer)
  cg.cvtsi2sd(X6, Rdx);              // kd

  // r = (z - chi - clo) * invc
  cg.movsdReg(X7, X5);
  cg.subsd(X7, X3);
  cg.subsd(X7, X4);
  cg.mulsd(X7, X1);                  // X7 = r

  // w = kd*Ln2hi + logc; hi = w + r; lo = w - hi + r + kd*Ln2lo
  loadConst(cg, X8, kLogLn2hi);
  cg.mulsd(X8, X6);                  // kd*Ln2hi
  cg.addsd(X8, X2);                  // w
  cg.movsdReg(X9, X8);
  cg.addsd(X9, X7);                  // hi
  cg.movsdReg(X10, X8);
  cg.subsd(X10, X9);                 // w - hi
  cg.addsd(X10, X7);                 // + r
  loadConst(cg, X11, kLogLn2lo);
  cg.mulsd(X11, X6);                 // kd*Ln2lo
  cg.addsd(X10, X11);                // lo

  // r2 = r*r
  cg.movsdReg(X8, X7);
  cg.mulsd(X8, X8);                  // X8 = r2
  // poly = r2*A0 + r*r2*(A1 + r*A2 + r2*(A3 + r*A4))
  cg.movsdReg(X11, X7);
  cg.mulsd(X11, X8);                 // r*r2
  loadConst(cg, X6, kLogA4);
  cg.mulsd(X6, X7);
  loadConst(cg, X3, kLogA3);
  cg.addsd(X3, X6);                  // A3 + r*A4
  cg.mulsd(X3, X8);                  // r2*(...)
  loadConst(cg, X6, kLogA2);
  cg.mulsd(X6, X7);
  cg.addsd(X3, X6);
  loadConst(cg, X6, kLogA1);
  cg.addsd(X3, X6);                  // A1 + ...
  cg.mulsd(X11, X3);                 // r*r2*(...)
  loadConst(cg, X6, kLogA0);
  cg.mulsd(X6, X8);                  // r2*A0
  cg.addsd(X11, X6);                 // + r2*A0
  // y = lo + poly + hi
  cg.addsd(X11, X10);                // + lo
  cg.addsd(X11, X9);                 // + hi
  cg.movsdReg(X0, X11);
  cg.jmp(done);

  cg.bind(retZero);
  cg.xorps(X0, X0);
  cg.jmp(done);
  cg.bind(retNegInf);
  loadConst(cg, X0, kNegInf);
  cg.jmp(done);
  cg.bind(retX);
  // X0 already holds x
  cg.jmp(done);
  cg.bind(retNaN);
  cg.movsdReg(X1, X0);
  cg.subsd(X1, X0);                  // x - x = nan
  cg.movsdReg(X0, X1);

  cg.bind(done);
  ret(cg);
}


