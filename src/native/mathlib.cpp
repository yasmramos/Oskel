// Emit a table of 64-bit little-endian words.
void emitU64Table(CodeGen& cg, const std::uint64_t* data, std::size_t count) {
  for (std::size_t i = 0; i < count; ++i) {
    std::uint8_t bytes[8];
    std::uint64_t v = data[i];
    for (int b = 0; b < 8; ++b) bytes[b] = static_cast<std::uint8_t>(v >> (8 * b));
    cg.emitBytes(bytes, 8);
  }
}

