// double exp_inline(double x, double xtail, uint32_t sign_bias)
//
// A direct port of musl's `exp_inline` (the core shared by `exp` and `pow`).
// `x` is in xmm0, `xtail` in xmm1, `sign_bias` in edx; the result returns in
// xmm0. It is a leaf (no calls), so no frame is needed and only volatile
// registers are touched. `refs.expTab` addresses the 256-entry table.
// `powVariant` selects `pow`'s `specialcase` (which has a signed scale and a
// `fabs` test) over `exp`'s (which tests `y < 1.0`).
void emitExpInline(CodeGen& cg, CodeGen::Label label, const ConstRefs& refs,
                   bool powVariant) {
  CodeGen::Label tiny = cg.newLabel();
  CodeGen::Label big = cg.newLabel();
  CodeGen::Label large = cg.newLabel();
  CodeGen::Label largeNotNegInf = cg.newLabel();
  CodeGen::Label uflow = cg.newLabel();
  CodeGen::Label oflow = cg.newLabel();
  CodeGen::Label normal = cg.newLabel();
  CodeGen::Label tinyDone = cg.newLabel();
  CodeGen::Label uflowSign = cg.newLabel();
  CodeGen::Label oflowSign = cg.newLabel();
  CodeGen::Label special = cg.newLabel();
  CodeGen::Label specialNeg = cg.newLabel();
  CodeGen::Label specialNegScale = cg.newLabel();
  CodeGen::Label haveOne = cg.newLabel();
  CodeGen::Label scaleOut = cg.newLabel();
  CodeGen::Label done = cg.newLabel();

  cg.bind(label);

  // abstop = (bits(x) >> 52) & 0x7ff, kept in rcx.
  cg.movqFromXmm(Rax, X0);           // rax = bits(x)
  cg.movReg(Rcx, Rax);
  cg.shrImm8(Rcx, 52);
  cg.andImm32(Rcx, 0x7ff);

  // if (abstop - 0x3c9 >= 0x3f) goto big   [unsigned; 0x408-0x3c9 = 0x3f]
  cg.movReg(R10, Rcx);
  cg.subRegImm32(R10, 0x3c9);
  cg.cmpImm32(R10, 0x3f);
  cg.jcc(Jcc::Ae, big);
  cg.jmp(normal);

  cg.bind(big);
  cg.cmpImm32(Rcx, 0x3c9);
  cg.jcc(Jcc::B, tiny);              // abstop < 0x3c9: tiny
  cg.cmpImm32(Rcx, 0x409);
  cg.jcc(Jcc::Ae, large);
  cg.xorReg(Rcx, Rcx);               // abstop = 0: force specialcase below
  cg.jmp(normal);

  cg.bind(tiny);
  loadConst(cg, X2, kOne);
  cg.addsd(X2, X0);                  // one = 1.0 + x
  cg.testReg(Rdx);
  cg.jcc(Jcc::Eq, tinyDone);
  loadConst(cg, X3, kSignMask);
  cg.xorps(X2, X3);                  // negate
  cg.jmp(tinyDone);
  cg.bind(tinyDone);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(large);
  cg.movImm(R10, static_cast<std::int64_t>(kNegInf));
  cg.cmpReg(Rax, R10);
  cg.jcc(Jcc::Ne, largeNotNegInf);
  cg.xorps(X0, X0);                  // exp(-inf) = 0.0
  cg.jmp(done);
  cg.bind(largeNotNegInf);
  cg.cmpImm32(Rcx, 0x7ff);
  cg.jcc(Jcc::Ae, tiny);             // inf or nan: 1.0 + x
  cg.testReg(Rax);
  cg.jcc(Jcc::S, uflow);
  cg.jmp(oflow);

  cg.bind(uflow);
  loadConst(cg, X2, kP767);
  cg.testReg(Rdx);
  cg.jcc(Jcc::Eq, uflowSign);
  loadConst(cg, X3, kSignMask);
  cg.xorps(X2, X3);
  cg.bind(uflowSign);
  loadConst(cg, X3, kP767);
  cg.mulsd(X2, X3);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(oflow);
  loadConst(cg, X2, kP769);
  cg.testReg(Rdx);
  cg.jcc(Jcc::Eq, oflowSign);
  loadConst(cg, X3, kSignMask);
  cg.xorps(X2, X3);
  cg.bind(oflowSign);
  loadConst(cg, X3, kP769);
  cg.mulsd(X2, X3);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(normal);
  loadConst(cg, X2, kExpInvLn2N);
  cg.mulsd(X2, X0);                  // z = InvLn2N * x
  loadConst(cg, X3, kExpShift);
  cg.movsdReg(X4, X2);
  cg.addsd(X4, X3);                  // kd = z + Shift
  cg.movqFromXmm(R9, X4);            // ki
  cg.subsd(X4, X3);                  // kd -= Shift
  loadConst(cg, X5, kExpNegLn2hiN);
  cg.mulsd(X5, X4);
  cg.addsd(X5, X0);                  // x + kd*hi
  loadConst(cg, X6, kExpNegLn2loN);
  cg.mulsd(X6, X4);
  cg.addsd(X5, X6);                  // r
  cg.addsd(X5, X1);                  // r += xtail

  cg.movReg(R10, R9);
  cg.andImm32(R10, static_cast<std::int32_t>(kN - 1));
  cg.shlImm8(R10, 1);
  cg.imulImm32(R10, R10, 8);         // byte offset of T[idx]
  cg.leaRipLabel(Rax, refs.expTab);
  cg.addReg(Rax, R10);
  cg.movsdToXmm(X7, Rax, 0);         // tail = T[idx]
  cg.movFromMem(R8, Rax, 8);         // T[idx+1]
  cg.movReg(R11, R9);
  cg.addReg(R11, Rdx);               // ki + sign_bias
  cg.shlImm8(R11, 52 - kExpTabBits); // top
  cg.addReg(R8, R11);                // sbits

  cg.movsdReg(X8, X5);
  cg.mulsd(X8, X8);                  // r2
  loadConst(cg, X9, kExpC3);
  cg.mulsd(X9, X5);
  loadConst(cg, X10, kExpC2);
  cg.addsd(X10, X9);
  cg.mulsd(X10, X8);
  cg.addsd(X10, X5);
  cg.addsd(X10, X7);                 // + tail
  loadConst(cg, X11, kExpC5);
  cg.mulsd(X11, X5);
  loadConst(cg, X9, kExpC4);
  cg.addsd(X9, X11);
  cg.movsdReg(X11, X8);
  cg.mulsd(X11, X8);                 // r2*r2
  cg.mulsd(X9, X11);
  cg.addsd(X10, X9);                 // tmp

  // if (abstop == 0) specialcase(tmp, sbits, ki)
  cg.testReg(Rcx);
  cg.jcc(Jcc::Ne, scaleOut);

  cg.bind(special);
  // if ((ki & 0x80000000) == 0): test bit 31 alone (test imm32 sign-extends).
  cg.movReg(R10, R9);
  cg.shlImm8(R10, 32);
  cg.testReg(R10);
  cg.jcc(Jcc::S, specialNeg);
  cg.movImm(Rax, 1009);
  cg.shlImm8(Rax, 52);
  cg.subReg(R8, Rax);                // sbits -= 1009 << 52
  cg.movqToXmm(X1, R8);              // scale
  cg.movsdReg(X2, X1);
  cg.mulsd(X2, X10);
  cg.addsd(X2, X1);
  loadConst(cg, X3, kP1009);
  cg.mulsd(X2, X3);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(specialNeg);
  cg.movImm(Rax, 1022);
  cg.shlImm8(Rax, 52);
  cg.addReg(R8, Rax);                // sbits += 1022 << 52
  cg.movqToXmm(X1, R8);              // scale (signed)
  cg.movsdReg(X2, X1);
  cg.mulsd(X2, X10);
  cg.addsd(X2, X1);                  // y = scale + scale*tmp
  if (powVariant) {
    // if (fabs(y) < 1.0)
    cg.movqFromXmm(Rax, X2);
    cg.movImm(R10, static_cast<std::int64_t>(kAbsMask));
    cg.andReg(Rax, R10);
    cg.movqToXmm(X3, Rax);           // |y|
    loadConst(cg, X4, kOne);
    cg.ucomisd(X3, X4);
    cg.jcc(Jcc::Ae, specialNegScale);
    // one = (y < 0) ? -1.0 : 1.0
    loadConst(cg, X4, kOne);
    cg.xorps(X5, X5);
    cg.ucomisd(X2, X5);
    cg.jcc(Jcc::Ae, haveOne);
    loadConst(cg, X4, kNegOne);
    cg.bind(haveOne);
  } else {
    // if (y < 1.0)
    loadConst(cg, X3, kOne);
    cg.ucomisd(X2, X3);
    cg.jcc(Jcc::Ae, specialNegScale);
    loadConst(cg, X4, kOne);         // one = 1.0
  }
  // lo = scale - y + scale*tmp
  cg.movsdReg(X5, X1);
  cg.subsd(X5, X2);
  cg.movsdReg(X6, X1);
  cg.mulsd(X6, X10);
  cg.addsd(X5, X6);                  // lo
  // hi = one + y; lo = one - hi + y + lo; y = (hi + lo) - one
  cg.movsdReg(X6, X4);
  cg.addsd(X6, X2);                  // hi
  cg.movsdReg(X7, X4);
  cg.subsd(X7, X6);
  cg.addsd(X7, X2);
  cg.addsd(X7, X5);                  // lo
  cg.addsd(X6, X7);
  cg.subsd(X6, X4);                  // - one
  cg.movsdReg(X2, X6);
  // Fix the sign of a zero result.
  cg.xorps(X5, X5);
  cg.ucomisd(X2, X5);
  cg.jcc(Jcc::Ne, specialNegScale);
  if (powVariant) {
    cg.movImm(R10, static_cast<std::int64_t>(kSignMask));
    cg.andReg(R8, R10);
    cg.movqToXmm(X2, R8);
  } else {
    cg.xorps(X2, X2);                // exp: y = 0.0
  }
  cg.bind(specialNegScale);
  loadConst(cg, X3, kPm1022);
  cg.mulsd(X2, X3);
  cg.movsdReg(X0, X2);
  cg.jmp(done);

  cg.bind(scaleOut);
  cg.movqToXmm(X1, R8);              // scale
  cg.movsdReg(X2, X1);
  cg.mulsd(X2, X10);
  cg.addsd(X2, X1);
  cg.movsdReg(X0, X2);

  cg.bind(done);
  ret(cg);
}

// The public `exp`: xtail = 0, sign_bias = 0, then the core.
void emitExpPublic(CodeGen& cg, CodeGen::Label label, CodeGen::Label core) {
  cg.bind(label);
  cg.xorps(X1, X1);
  cg.xorReg(Rdx, Rdx);
  cg.jmp(core);
}

